import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import pg from 'pg';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
for (const line of readFileSync(path.join(root, '.env'), 'utf8').split(/\r?\n/)) {
  const match = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
  if (match && !match[1].startsWith('#') && process.env[match[1]] === undefined) {
    process.env[match[1]] = match[2].replace(/^(['"])(.*)\1$/, '$2');
  }
}

if (!process.env.DATABASE_URL) throw new Error('Set DATABASE_URL in .env before migrating.');
const sourcePath = process.env.JIBONGUARD_DB || path.join(root, 'jibonguard.sqlite3');
const syncMode = process.argv.includes('--sync-before-cutover');
const sqlite = new DatabaseSync(sourcePath, { readOnly: true });
sqlite.exec('BEGIN');
const tables = sqlite.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
const indexes = sqlite.prepare("SELECT name,sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name").all();
const tableInfo = new Map(tables.map(({ name }) => [name, sqlite.prepare(`PRAGMA table_info("${name.replaceAll('"', '""')}")`).all()]));
const pgTypes = pg.types;
pgTypes.setTypeParser(20, value => {
  const parsed = Number(value);
  if (!Number.isSafeInteger(parsed)) throw new Error(`PostgreSQL integer is outside JavaScript's safe range: ${value}`);
  return parsed;
});
const client = new pg.Client({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 15000 });

function quoteIdentifier(value) {
  return `"${value.replaceAll('"', '""')}"`;
}

function postgresTableSql(sql) {
  return sql
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/\bCOLLATE\s+NOCASE\b/gi, '')
    .replace(/\s+WITHOUT\s+ROWID\b/gi, '');
}

function sortableTableOrder() {
  const pending = new Set(tables.map(table => table.name));
  const ordered = [];
  while (pending.size) {
    let progressed = false;
    for (const name of [...pending]) {
      const dependencies = sqlite.prepare(`PRAGMA foreign_key_list(${quoteIdentifier(name)})`).all()
        .map(row => row.table).filter(dep => dep !== name && pending.has(dep));
      if (dependencies.length) continue;
      ordered.push(name);
      pending.delete(name);
      progressed = true;
    }
    if (!progressed) {
      // Resolve uncommon cycles by creating their tables without depending on creation order;
      // PostgreSQL can add the foreign keys afterward.
      ordered.push(...pending);
      break;
    }
  }
  return ordered;
}

function canonicalRow(row) {
  return JSON.stringify(row, (_key, value) => typeof value === 'bigint' ? value.toString() : value);
}

try {
  await client.connect();
  const existing = await client.query("SELECT table_name FROM information_schema.tables WHERE table_schema='public' AND table_type='BASE TABLE' ORDER BY table_name");
  if (!syncMode && existing.rowCount !== 0) throw new Error('Target PostgreSQL schema is no longer empty; migration stopped without changing it.');
  if (syncMode && existing.rowCount === 0) throw new Error('Sync mode requires an already migrated PostgreSQL schema.');
  if (syncMode) {
    const targetNames = new Set(existing.rows.map(row => row.table_name));
    const missing = tables.map(table => table.name).filter(name => !targetNames.has(name));
    if (missing.length) throw new Error(`Sync stopped because PostgreSQL is missing expected tables: ${missing.join(', ')}.`);
  }

  await client.query('BEGIN');
  const orderedTables = syncMode ? tables.map(table => table.name) : sortableTableOrder();
  if (!syncMode) {
    const ordered = sortableTableOrder();
    const created = new Set();
    const definitions = [];
    for (const name of ordered) {
      definitions.push(postgresTableSql(tables.find(table => table.name === name).sql));
      created.add(name);
    }
    // One round trip for the schema avoids a network round trip per table.
    await client.query(definitions.join(';\n'));
    if (indexes.length) await client.query(indexes.map(({ sql }) => sql.replace(/\bCOLLATE\s+NOCASE\b/gi, '')).join(';\n'));
    await client.query('CREATE UNIQUE INDEX users_email_casefold_idx ON users (LOWER(email)); CREATE UNIQUE INDEX admin_users_email_casefold_idx ON admin_users (LOWER(email));');
  }

  const sourceSnapshot = new Map();
  for (const name of orderedTables) {
    const columns = tableInfo.get(name).map(column => column.name);
    const primaryKey = tableInfo.get(name).filter(column => column.pk).sort((a, b) => a.pk - b.pk).map(column => column.name);
    if (!primaryKey.length) throw new Error(`Cannot safely migrate ${name}: it has no primary key.`);
    const qTable = quoteIdentifier(name);
    const qColumns = columns.map(quoteIdentifier).join(',');
    const sourceRows = sqlite.prepare(`SELECT * FROM ${qTable} ORDER BY ${columns.map(quoteIdentifier).join(',')}`).all();
    const hash = createHash('sha256');
    const batchSize = Math.max(1, Math.min(400, Math.floor(50000 / columns.length)));
    const conflictSql = syncMode
      ? ` ON CONFLICT (${primaryKey.map(quoteIdentifier).join(',')}) ${columns.some(column => !primaryKey.includes(column)) ? `DO UPDATE SET ${columns.filter(column => !primaryKey.includes(column)).map(column => `${quoteIdentifier(column)}=EXCLUDED.${quoteIdentifier(column)}`).join(',')}` : 'DO NOTHING'}`
      : '';
    sourceSnapshot.set(name, { rows: sourceRows, primaryKey });
    for (let offset = 0; offset < sourceRows.length; offset += batchSize) {
      const batch = sourceRows.slice(offset, offset + batchSize);
      const values = [];
      const tuples = batch.map((row, rowIndex) => {
        for (const column of columns) values.push(row[column]);
        const first = rowIndex * columns.length + 1;
        return `(${columns.map((_, columnIndex) => `$${first + columnIndex}`).join(',')})`;
      });
      await client.query(`INSERT INTO ${qTable} (${qColumns}) VALUES ${tuples.join(',')}${conflictSql}`, values);
    }
    for (const row of sourceRows) { hash.update(canonicalRow(row)); hash.update('\n'); }
    sourceSnapshot.get(name).count = sourceRows.length;
    sourceSnapshot.get(name).hash = hash.digest('hex');
  }

  for (const name of orderedTables) {
    const info = tableInfo.get(name);
    const identity = info.find(column => column.pk && /^INTEGER$/i.test(column.type));
    if (identity) {
      const sequence = await client.query('SELECT pg_get_serial_sequence($1,$2) AS name', [name, identity.name]);
      if (sequence.rows[0].name) {
        const max = await client.query(`SELECT MAX(${quoteIdentifier(identity.name)}) AS value FROM ${quoteIdentifier(name)}`);
        if (max.rows[0].value !== null) {
          await client.query('SELECT setval($1, $2, true)', [sequence.rows[0].name, max.rows[0].value]);
        }
      }
    }
  }

  for (const name of orderedTables) {
    const info = tableInfo.get(name);
    const columns = info.map(column => column.name);
    const qTable = quoteIdentifier(name);
    const rows = await client.query(`SELECT * FROM ${qTable} ORDER BY ${columns.map(column => `${quoteIdentifier(column)} ASC NULLS FIRST`).join(',')}`);
    const expected = sourceSnapshot.get(name);
    if (syncMode) {
      const byKey = new Map(rows.rows.map(row => [canonicalRow(Object.fromEntries(expected.primaryKey.map(column => [column, row[column]]))), row]));
      for (const sourceRow of expected.rows) {
        const key = canonicalRow(Object.fromEntries(expected.primaryKey.map(column => [column, sourceRow[column]])));
        if (canonicalRow(byKey.get(key)) !== canonicalRow(sourceRow)) throw new Error(`Data verification failed for ${name}; the PostgreSQL transaction will be rolled back.`);
      }
    } else {
      const hash = createHash('sha256');
      for (const row of rows.rows) { hash.update(canonicalRow(row)); hash.update('\n'); }
      if (rows.rowCount !== expected.count || hash.digest('hex') !== expected.hash) {
        throw new Error(`Data verification failed for ${name}; the PostgreSQL transaction will be rolled back.`);
      }
    }
  }

  await client.query('COMMIT');
  console.log(`${syncMode ? 'SQLite sync complete' : 'Migration complete'}: ${orderedTables.length} tables copied and source rows verified${syncMode ? '; PostgreSQL-only historical rows were retained.' : ' by row count and SHA-256 content hash.'}`);
  for (const name of orderedTables) console.log(`${name}\t${sourceSnapshot.get(name).count}`);
} catch (error) {
  try { await client.query('ROLLBACK'); } catch {}
  throw error;
} finally {
  sqlite.exec('ROLLBACK');
  sqlite.close();
  await client.end().catch(() => {});
}
